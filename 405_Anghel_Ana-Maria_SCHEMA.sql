CREATE TABLE TIP_DOCUMENT (
    id_tip      NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    denumire    VARCHAR2(100) NOT NULL,
    descriere   VARCHAR2(500),
    CONSTRAINT pk_tip_document PRIMARY KEY (id_tip),
    CONSTRAINT uq_tip_document_denumire UNIQUE (denumire)
);

CREATE TABLE CANDIDAT (
    id_candidat   NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    nume          VARCHAR2(50) NOT NULL,
    prenume       VARCHAR2(50) NOT NULL,
    data_nastere  DATE NOT NULL,
    sex           CHAR(1),
    email         VARCHAR2(100) NOT NULL,
    telefon       VARCHAR2(15),
    CONSTRAINT pk_candidat PRIMARY KEY (id_candidat),
    CONSTRAINT uq_candidat_identitate UNIQUE (nume, prenume, data_nastere),
    CONSTRAINT uq_candidat_email UNIQUE (email),
    CONSTRAINT chk_candidat_sex CHECK (sex IN ('M','F')),
    CONSTRAINT chk_candidat_email CHECK (
        REGEXP_LIKE(email, '^[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}$')
    ),
    CONSTRAINT chk_candidat_telefon CHECK (
        telefon IS NULL OR REGEXP_LIKE(telefon, '^(\+4|0)[0-9]{9,10}$')
    )
);

CREATE TABLE PROGRAM_STUDIU (
    id_program        NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    denumire          VARCHAR2(150) NOT NULL,
    forma_invatamant  VARCHAR2(20) NOT NULL,
    nivel             VARCHAR2(20) NOT NULL,
    durata_ani        NUMBER(1) NOT NULL,
    nr_locuri         NUMBER NOT NULL,
    CONSTRAINT pk_program_studiu PRIMARY KEY (id_program),
    CONSTRAINT chk_program_forma CHECK (forma_invatamant IN ('IF','ID','IFR')),
    CONSTRAINT chk_program_nivel CHECK (nivel IN ('Licenta','Master','Doctorat')),
    CONSTRAINT chk_program_durata CHECK (durata_ani BETWEEN 1 AND 6),
    CONSTRAINT chk_program_locuri CHECK (nr_locuri > 0)
);

CREATE TABLE UNIVERSITATE (
    id_universitate       NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    denumire_universitate VARCHAR2(150) NOT NULL,
    CONSTRAINT pk_universitate PRIMARY KEY (id_universitate),
    CONSTRAINT uq_universitate_denumire UNIQUE (denumire_universitate)
);

CREATE TABLE FACULTATE (
    id_institutie    NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    denumire         VARCHAR2(150) NOT NULL,
    descriere        VARCHAR2(500),
    telefon          VARCHAR2(15),
    adresa           VARCHAR2(200),
    id_universitate  NUMBER NOT NULL,
    CONSTRAINT pk_facultate PRIMARY KEY (id_institutie),
    CONSTRAINT uq_facultate_denumire UNIQUE (denumire, id_universitate),
    CONSTRAINT chk_facultate_telefon CHECK (
        telefon IS NULL OR REGEXP_LIKE(telefon, '^(\+4|0)[0-9]{9,10}$')
    ),
    CONSTRAINT fk_facultate_universitate FOREIGN KEY (id_universitate)
        REFERENCES UNIVERSITATE(id_universitate)
        ON DELETE CASCADE
);

CREATE TABLE ARE (
    id_program_studiu  NUMBER NOT NULL,
    id_facultate       NUMBER NOT NULL,
    CONSTRAINT pk_are PRIMARY KEY (id_program_studiu, id_facultate),
    CONSTRAINT fk_are_program FOREIGN KEY (id_program_studiu)
        REFERENCES PROGRAM_STUDIU(id_program)
        ON DELETE CASCADE,
    CONSTRAINT fk_are_facultate FOREIGN KEY (id_facultate)
        REFERENCES FACULTATE(id_institutie)
        ON DELETE CASCADE
);

CREATE TABLE DOSAR (
    id_dosar          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    data_depunere     DATE NOT NULL,
    status_dosar      VARCHAR2(20) DEFAULT 'IN_CURS' NOT NULL,
    nota_admitere     NUMBER(4,2),
    id_candidat       NUMBER NOT NULL,
    id_program_studiu NUMBER NOT NULL,
    CONSTRAINT pk_dosar PRIMARY KEY (id_dosar),
    CONSTRAINT uq_dosar_candidat_program UNIQUE (id_candidat, id_program_studiu),
    CONSTRAINT chk_dosar_status CHECK (status_dosar IN ('IN_CURS','APROBAT','RESPINS')),
    CONSTRAINT chk_dosar_nota CHECK (nota_admitere BETWEEN 1 AND 10),
    CONSTRAINT fk_dosar_candidat FOREIGN KEY (id_candidat)
        REFERENCES CANDIDAT(id_candidat)
        ON DELETE CASCADE,
    CONSTRAINT fk_dosar_program FOREIGN KEY (id_program_studiu)
        REFERENCES PROGRAM_STUDIU(id_program)
);

CREATE TABLE DOCUMENT (
    id_document        NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    data_incarcare     DATE DEFAULT SYSDATE NOT NULL,
    fisier             VARCHAR2(300) NOT NULL,
    status_verificare  VARCHAR2(20) DEFAULT 'NEVERIFICAT' NOT NULL,
    observatii         VARCHAR2(500),
    id_tip             NUMBER NOT NULL,
    CONSTRAINT pk_document PRIMARY KEY (id_document),
    CONSTRAINT chk_document_status CHECK (status_verificare IN ('NEVERIFICAT','VALIDAT','RESPINS')),
    CONSTRAINT fk_document_tip FOREIGN KEY (id_tip)
        REFERENCES TIP_DOCUMENT(id_tip)
);

CREATE TABLE CONTINE (
    id_document NUMBER NOT NULL,
    id_dosar    NUMBER NOT NULL,
    CONSTRAINT pk_contine PRIMARY KEY (id_document, id_dosar),
    CONSTRAINT fk_contine_document FOREIGN KEY (id_document)
        REFERENCES DOCUMENT(id_document)
        ON DELETE CASCADE,
    CONSTRAINT fk_contine_dosar FOREIGN KEY (id_dosar)
        REFERENCES DOSAR(id_dosar)
        ON DELETE CASCADE
);

CREATE TABLE TIP_PROBA (
    id_tip    NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    tip       VARCHAR2(50) NOT NULL,
    pondere   NUMBER(3,2) NOT NULL,
    CONSTRAINT pk_tip_proba PRIMARY KEY (id_tip),
    CONSTRAINT uq_tip_proba_denumire UNIQUE (tip),
    CONSTRAINT chk_tip_proba_pondere CHECK (pondere > 0 AND pondere <= 1)
);

CREATE TABLE PROBA_ADMITERE (
    id_proba    NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    data_proba  DATE NOT NULL,
    denumire    VARCHAR2(150) NOT NULL,
    descriere   VARCHAR2(500),
    id_tip      NUMBER NOT NULL,
    CONSTRAINT pk_proba_admitere PRIMARY KEY (id_proba),
    CONSTRAINT fk_proba_tip FOREIGN KEY (id_tip)
        REFERENCES TIP_PROBA(id_tip)
);

CREATE TABLE SE_INSCRIE_LA (
    id_candidat        NUMBER NOT NULL,
    id_program_studiu  NUMBER NOT NULL,
    id_proba           NUMBER NOT NULL,
    CONSTRAINT pk_se_inscrie_la PRIMARY KEY (id_candidat, id_program_studiu, id_proba),
    CONSTRAINT fk_inscrie_candidat FOREIGN KEY (id_candidat)
        REFERENCES CANDIDAT(id_candidat)
        ON DELETE CASCADE,
    CONSTRAINT fk_inscrie_program FOREIGN KEY (id_program_studiu)
        REFERENCES PROGRAM_STUDIU(id_program),
    CONSTRAINT fk_inscrie_proba FOREIGN KEY (id_proba)
        REFERENCES PROBA_ADMITERE(id_proba)
);

CREATE TABLE PROFESOR_CORECTOR (
    id_profesor     NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    nume            VARCHAR2(50) NOT NULL,
    prenume         VARCHAR2(50) NOT NULL,
    grad            VARCHAR2(50),
    data_inscriere  DATE DEFAULT SYSDATE NOT NULL,
    id_coordonator  NUMBER,
    CONSTRAINT pk_profesor_corector PRIMARY KEY (id_profesor),
    CONSTRAINT uq_profesor_identitate UNIQUE (nume, prenume, data_inscriere),
    CONSTRAINT chk_profesor_nu_e_propriul_coord CHECK (id_profesor <> id_coordonator),
    CONSTRAINT fk_profesor_coordonator FOREIGN KEY (id_coordonator)
        REFERENCES PROFESOR_CORECTOR(id_profesor)
        ON DELETE SET NULL
);

CREATE TABLE EVALUEAZA (
    id_proba    NUMBER NOT NULL,
    id_profesor NUMBER NOT NULL,
    CONSTRAINT pk_evalueaza PRIMARY KEY (id_proba, id_profesor),
    CONSTRAINT fk_evalueaza_proba FOREIGN KEY (id_proba)
        REFERENCES PROBA_ADMITERE(id_proba)
        ON DELETE CASCADE,
    CONSTRAINT fk_evalueaza_profesor FOREIGN KEY (id_profesor)
        REFERENCES PROFESOR_CORECTOR(id_profesor)
        ON DELETE CASCADE
);

